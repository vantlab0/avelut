const sanitizeId = (name: string) =>
  name.toLowerCase().replace(/[^a-z0-9]/g, '_').replace(/_+/g, '_').replace(/^_|_$/g, '');

// Deduplicated & alphabetically sorted
export const SORTED_NIGERIAN_UNIVERSITIES = Array.from(new Set(NIGERIAN_UNIVERSITIES))
  .sort((a, b) => a.localeCompare(b));

export interface UniversityOption {
  id: string;
  name: string;
  short_name?: string;
}

export const HARDCODED_UNIVERSITY_OPTIONS: UniversityOption[] = SORTED_NIGERIAN_UNIVERSITIES.map(name => {
  let short_name: string | undefined;
  const match = name.match(/\(([^)]+)\)/);
  if (match) {
    short_name = match[1];
  }
  return {
    id: sanitizeId(name),
    name,
    short_name
  };
});
