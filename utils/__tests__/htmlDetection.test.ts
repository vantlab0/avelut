import { describe, it, expect } from 'vitest';
import { isAppIndexHtmlPayload } from '../inference';

describe('isAppIndexHtmlPayload', () => {
  it('does NOT reject fenced code blocks containing html', () => {
    const codeResponse = '```html\n<!DOCTYPE html>\n<html>\n<head><title>Test</title></head>\n<body><div id="root"></div></body>\n</html>\n```';
    expect(isAppIndexHtmlPayload(codeResponse)).toBe(false);
  });

  it('does NOT reject legitimate HTML documents generated by AI without app shell markers', () => {
    const htmlResponse = '<!DOCTYPE html>\n<html>\n<head><title>My Website</title></head>\n<body>\n<div id="root">My custom app</div>\n</body>\n</html>';
    expect(isAppIndexHtmlPayload(htmlResponse)).toBe(false);
  });

  it('detects and rejects actual app shell index.html fallback', () => {
    const appShellHtml = '<!DOCTYPE html>\n<html lang="en">\n<head>\n<script type="module" src="/index.tsx"></script>\n</head>\n<body>\n<div id="root">\n<div id="app-launch-skeleton"></div>\n</div>\n</body>\n</html>';
    expect(isAppIndexHtmlPayload(appShellHtml)).toBe(true);
  });
});
